// Copies design-system/components/bundle.css into src/styles/boo-components.css
// without its Google Fonts @import. The app loads its fonts from npm (Fontsource),
// so nothing reaches Google at build time or in the browser.
// Run after updating design-system/: npm run ds:sync
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const SOURCE = `${root}design-system/components/bundle.css`;
export const TARGET = `${root}src/styles/boo-components.css`;

const HEADER =
  "/* generated by scripts/sync-design-system.mjs from design-system/components/bundle.css.\n" +
  "   do not edit: change the design system and run npm run ds:sync. */\n";

export function buildComponentsCss(source) {
  const withoutRemoteImports = source
    .split("\n")
    .filter((line) => !/^\s*@import\s+url\(["']?https?:/.test(line))
    .join("\n")
    .replace(/^\n+/, "");
  return HEADER + withoutRemoteImports;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, buildComponentsCss(readFileSync(SOURCE, "utf8")));
  console.log("wrote", TARGET);
}
